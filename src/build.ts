/** Render every slice for both themes, then write README.md and preview.html. */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import config from "../profile.config.ts";
import type { StackStats } from "./aggregate.ts";
import { header, HALF, lifecycle, linkButton, offline, projectCard, projectsTitle, response, stack, W } from "./render.ts";
import type { Svg } from "./svg.ts";
import { esc } from "./svg.ts";
import { themes, type Theme } from "./theme.ts";

const root = new URL("../", import.meta.url);
const file = (p: string) => new URL(p, root);

function loadStats(): StackStats | null {
  for (const [p, sample] of [["data/stack.json", false], ["data/stack.sample.json", true]] as const) {
    if (existsSync(file(p))) return { ...(JSON.parse(readFileSync(file(p), "utf8")) as StackStats), ...(sample ? { sample: true } : {}) };
  }
  return null;
}

interface Item {
  name: string;
  /** Percentage of the README width. */
  width: number;
  href?: string;
  /** Images that must sit side by side are emitted without whitespace between them. */
  inline?: boolean;
  make: (t: Theme) => Svg;
}

function items(stats: StackStats | null): Item[] {
  const full = (name: string, make: (t: Theme) => Svg): Item => ({ name, width: 100, make });
  const list: Item[] = [
    full("header", (t) => header(config, t)),
    full("lifecycle", (t) => lifecycle(config, t)),
    full("response", (t) => response(config, t)),
    full("stack", (t) => stack(stats, t)),
    full("offline", (t) => offline(config, t)),
  ];
  const projects = config.projects.slice(0, 4);
  if (projects.length) {
    list.push(full("projects", (t) => projectsTitle(t)));
    projects.forEach((p, i) =>
      list.push({
        name: `project-${i + 1}`,
        width: (HALF / W) * 100,
        href: p.url,
        inline: i % 2 === 1,
        make: (t) => projectCard(p, i % 2 ? "right" : "left", projects, t),
      }),
    );
  }
  const links: [string, "GET" | "POST", string, string | undefined][] = [
    ["contact", "POST", "/contact", config.links.email && `mailto:${config.links.email}`],
    ["website", "GET", "/website", config.links.website],
  ];
  links
    .filter(([, , , href]) => href)
    .forEach(([name, method, path, href], i) => {
      const probe = linkButton(method, path, themes[0]!);
      list.push({ name, width: (probe.width / W) * 100, href, inline: i > 0, make: (t) => linkButton(method, path, t) });
    });
  return list;
}

const pct = (n: number) => `${Number(n.toFixed(2))}%`;

function picture(it: Item, alt: string) {
  const img =
    `<picture><source media="(prefers-color-scheme: dark)" srcset="./assets/dark/${it.name}.svg">` +
    `<img src="./assets/light/${it.name}.svg" alt="${esc(alt)}" width="${pct(it.width)}"></picture>`;
  return it.href ? `<a href="${esc(it.href)}">${img}</a>` : img;
}

async function main() {
  const stats = loadStats();
  const list = items(stats);

  for (const t of themes) {
    const dir = file(`assets/${t.name}/`);
    mkdirSync(dir, { recursive: true });
    // Drop slices that no longer exist (e.g. fewer projects). Locally deletes may be blocked; that's fine.
    const keep = new Set(list.map((i) => `${i.name}.svg`));
    for (const f of readdirSync(dir)) if (!keep.has(f)) try { rmSync(new URL(f, dir)); } catch { /* ignore */ }
  }

  const alts = new Map<string, string>();
  for (const it of list) {
    for (const t of themes) {
      const svg = it.make(t);
      alts.set(it.name, svg.title);
      writeFileSync(file(`assets/${t.name}/${it.name}.svg`), await svg.toString());
    }
  }

  // README: one line per row; side-by-side images are glued to the previous one.
  const rows: string[] = [];
  for (const it of list) {
    const html = picture(it, alts.get(it.name)!);
    if (it.inline && rows.length) rows[rows.length - 1] += html;
    else rows.push(html);
  }
  const readme = [
    "<!-- Generated by `npm run build` from profile.config.ts and data/stack.json. Edit those, not this file. -->",
    '<div align="center">',
    ...rows,
    "</div>",
    "",
  ].join("\n");
  writeFileSync(file("README.md"), readme);

  const col = (t: Theme, bg: string) =>
    `<div style="background:${bg};padding:24px;width:${W}px">` +
    rows.map((r) => `<div style="line-height:0">${r.replaceAll("./assets/light/", `./assets/${t.name}/`).replace(/<source[^>]*>/g, "")}</div>`).join("") +
    `</div>`;
  writeFileSync(
    file("preview.html"),
    `<!doctype html><meta charset="utf-8"><title>Profile preview</title><body style="margin:0;display:flex;gap:24px;flex-wrap:wrap;background:#888">${col(themes[0]!, "#0d1117")}${col(themes[1]!, "#ffffff")}</body>\n`,
  );

  console.log(`Rendered ${list.length} slices × ${themes.length} themes${stats?.sample ? " (sample data)" : stats ? "" : " (no stack data yet)"}.`);
}

await main();
